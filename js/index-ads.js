/* =========================================================
   AD ROTATION TIME
   ---------------------------------------------------------
   5000 = 5 seconds
   اگر 10 seconds کرنا ہو تو 10000 لکھیں۔
========================================================= */

const AD_ROTATION_TIME = 5000;


/* =========================================================
   PAGE AD SYSTEM
   ---------------------------------------------------------
   یہ function page پر موجود تمام ad slots تلاش کرتا ہے
   اور انہیں automatic ads دکھاتا ہے۔
========================================================= */

function showAds() {

    /* -----------------------------------------------------
       PAGE کے تمام AD SLOTS تلاش کریں
       -----------------------------------------------------
       HTML میں جہاں بھی یہ class ہوگی:

       <div class="ad-content"></div>

       وہاں ad automatically show ہوگا۔
    ----------------------------------------------------- */

    const adSlots = document.querySelectorAll(".ad-content");


    /* اگر page پر کوئی ad slot موجود نہیں */
    if (adSlots.length === 0) {

        console.log("No ad slot found");

        return;
    }


    /* -----------------------------------------------------
       CHECK کریں کہ ads.js load ہوئی ہے یا نہیں
    ----------------------------------------------------- */

    if (typeof ads === "undefined" || ads.length === 0) {

        console.log("Ads data not found");

        return;
    }


    /* =====================================================
       RANDOM ADS SELECT کرنا
       -----------------------------------------------------
       ہر slot کے لیے random ad منتخب ہوگا۔
       
       مثال:

       Left  = Ad 1
       Right = Ad 4

       اگلی rotation:

       Left  = Ad 3
       Right = Ad 2
    ===================================================== */

    const shuffledAds = [...ads].sort(() => Math.random() - 0.5);


    /* -----------------------------------------------------
       ہر AD SLOT میں الگ advertisement لگائیں
    ----------------------------------------------------- */

    adSlots.forEach(function(slot, index) {


        /* -------------------------------------------------
           اگر ads زیادہ ہیں تو random shuffled list سے
           مختلف ad استعمال ہوگا۔
        ------------------------------------------------- */

        const ad = shuffledAds[index % shuffledAds.length];


        /* =================================================
           AD HTML
           -------------------------------------------------
           یہاں image، product name اور product URL
           page پر load ہوتے ہیں۔
        ================================================= */

        slot.innerHTML = `

            <a
                href="${ad.url}"
                class="ad-product-link"
                target="_blank"
                rel="noopener noreferrer"
            >

                <!-- PRODUCT IMAGE -->

                <img
                    src="${ad.image}"
                    alt="${ad.name}"
                    class="ad-product-image"
                >


                <!-- PRODUCT NAME -->

                <h3>
                    ${ad.name}
                </h3>

            </a>

        `;

    });

}


/* =========================================================
   PAGE LOAD
   ---------------------------------------------------------
   جب HTML مکمل load ہو جائے تو پہلی بار ads دکھائیں۔
========================================================= */

document.addEventListener("DOMContentLoaded", function() {


    /* -----------------------------------------------------
       پہلی دفعہ فوراً ads دکھائیں
    ----------------------------------------------------- */

    showAds();


    /* =====================================================
       AUTOMATIC AD ROTATION
       -----------------------------------------------------
       ہر 5 seconds بعد showAds() دوبارہ چلے گا۔

       5000 milliseconds = 5 seconds
    ===================================================== */

    setInterval(function() {

        showAds();

    }, AD_ROTATION_TIME);

});
